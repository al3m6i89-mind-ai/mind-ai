#!/usr/bin/env python3
"""Rebuilds firebase/cloudshell-deploy.sh from functions/ and firebase/*.

Run after changing functions/index.js, functions/package.json,
firebase/firestore.rules or firebase/firestore.indexes.json:
    python3 tool/make_cloudshell.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = {
    'functions/package.json': '__MINDAI_PKG__',
    'functions/index.js': '__MINDAI_JS__',
    'firebase/firestore.rules': '__MINDAI_RULES__',
    'firebase/firestore.indexes.json': '__MINDAI_INDEXES__',
}

parts = ['''#!/bin/bash
# Deploys the Mind Ai Cloud Functions (push notifications, reports), the
# Firestore rules and the Firestore indexes to chat-f9edd from Google Cloud
# Shell (console.cloud.google.com, the >_ icon) with your own Google account:
# no service-account key needed. Paste this whole file into Cloud Shell and press Enter.
# Generated by tool/make_cloudshell.py; don't edit by hand.
set -e
PROJECT=chat-f9edd
rm -rf ~/mindai-deploy && mkdir -p ~/mindai-deploy/functions ~/mindai-deploy/firebase && cd ~/mindai-deploy
gcloud config set project "$PROJECT" >/dev/null

cat > firebase.json <<'__MINDAI_CFG__'
{
  "firestore": { "rules": "firebase/firestore.rules", "indexes": "firebase/firestore.indexes.json" },
  "functions": [{ "source": "functions", "codebase": "default", "runtime": "nodejs20" }]
}
__MINDAI_CFG__
''']
for path, marker in files.items():
    text = (root / path).read_text()
    assert marker not in text, f'{marker} appears inside {path}'
    if not text.endswith('\n'):
        text += '\n'
    parts.append(f"\ncat > {path} <<'{marker}'\n{text}{marker}\n")

parts.append('''
# The functions must run where the database lives.
LOC=$(gcloud firestore databases describe --database='(default)' --format='value(locationId)' 2>/dev/null || true)
case "$LOC" in
  nam5|"") REGION=us-central1 ;;
  nam7) REGION=us-east4 ;;
  eur3) REGION=europe-west1 ;;
  *) REGION=$LOC ;;
esac
echo "FN_REGION=$REGION" > functions/.env
echo ">> Firestore: ${LOC:-?}  ->  functions region: $REGION"

(cd functions && npm install --omit=dev --no-audit --no-fund --loglevel=error)
npx --yes firebase-tools@14 deploy --only functions,firestore --project "$PROJECT" --force
echo ">> DONE: functions, rules and indexes deployed (indexes finish building in a few minutes)."
''')
out = root / 'firebase/cloudshell-deploy.sh'
out.write_text(''.join(parts))
out.chmod(0o755)
print(f'wrote {out}')
